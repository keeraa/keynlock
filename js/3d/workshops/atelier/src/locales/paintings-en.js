const CENTURIES = { I: 1, V: 5, X: 10 };
const romanToNumber = roman => [...roman].reduce((total, letter, i, all) => {
  const value = CENTURIES[letter], next = CENTURIES[all[i + 1]] ?? 0;
  return total + (value < next ? -value : value);
}, 0);
const ordinal = n => `${n}${n % 100 >= 11 && n % 100 <= 13 ? 'th' : ['th', 'st', 'nd', 'rd'][n % 10] ?? 'th'}`;

/** A Russian date as written in the catalog, in English: "ок. 1831", "1480-е", "конец XVIII века". */
export function englishYear(year) {
  return String(year)
    .replace(/^(?:ок\.|около)\s*/, 'c. ')
    .replace(/^конец\s+(\d+)-х$/, 'late $1s')
    .replace(/(\d+)-е$/, '$1s')
    .replace(/^конец\s+([IVX]+)\s+века$/, (m, roman) => `late ${ordinal(romanToNumber(roman))} century`)
    .replace(/^([IVX]+)\s+век$/, (m, roman) => `${ordinal(romanToNumber(roman))} century`);
}
